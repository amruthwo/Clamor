#!/usr/bin/env python3
"""Build crates/clamor-node/src/icons.svg (and its copy apps/desktop/ui/icons.svg): the Material Symbols (Rounded, weight 400) that the
dashboard and the app use, as one SVG sprite of <symbol id="i-NAME">. It ships inside Clamor, so
the UI needs no network (swarms run on a LAN, often offline).

Icons: Material Symbols by Google, Apache License 2.0 (npm @material-symbols/svg-400).
The crab (the Coordinator tab) is Clamor's own, drawn on the same grid.

Usage: tools/gen-icons.py            (add a name to ICONS, run again, commit icons.svg)
"""
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

VERSION = "0.40.2"
BASE = f"https://cdn.jsdelivr.net/npm/@material-symbols/svg-400@{VERSION}/rounded/"

# name, or name+ for both the outlined and the filled ("-fill") version.
ICONS = """
chat_bubble+ hub+ neurology+ settings+ menu add_circle arrow_upward stop content_copy thumb_up thumb_down
edit_square groups person lock check build psychology visibility visibility_off data_array download description
laptop_mac desktop_windows mobile computer dns memory speed battery_charging_full low_priority
volunteer_activism chevron_right close add person_add person_remove do_not_disturb_on pause_circle play_circle
tune qr_code_2 mobile_arrow_down swap_horiz update monitoring info key badge login logout move_up lan
article timer how_to_reg pin image photo_camera arrow_back error warning check_circle refresh schedule
terminal more_vert delete edit dark_mode light_mode brightness_auto power_settings_new folder_open
open_in_new keyboard_arrow_down hourglass_top cloud_off bolt
""".split()

CRAB = """<g fill="none" stroke="currentColor" stroke-width="1.8" stroke-linecap="round" stroke-linejoin="round">
<ellipse cx="12" cy="14.5" rx="5.6" ry="3.9" fill="{f}"/><path d="M10.2 10.7 9.6 8.4M13.8 10.7l.6-2.3"/>
<circle cx="9.4" cy="7.4" r=".9" fill="currentColor" stroke="none"/><circle cx="14.6" cy="7.4" r=".9" fill="currentColor" stroke="none"/>
<path d="M6.9 12.6 4.6 9.6M17.1 12.6l2.3-3"/>
<path d="M4.6 9.6C2.9 8.9 2.5 6.4 3.9 4.9c.3 1.3 1.1 1.9 2.2 1.8-.2 1.3-.7 2.3-1.5 2.9Z" fill="{f}"/>
<path d="M19.4 9.6c1.7-.7 2.1-3.2.7-4.7-.3 1.3-1.1 1.9-2.2 1.8.2 1.3.7 2.3 1.5 2.9Z" fill="{f}"/>
<path d="M6.6 15.6 3.8 16.8M7.4 17.5l-2.2 2M17.4 15.6l2.8 1.2M16.6 17.5l2.2 2"/></g>"""


def fetch(name: str) -> str | None:
    try:
        with urllib.request.urlopen(BASE + name + ".svg", timeout=30) as r:
            svg = r.read().decode()
    except urllib.error.HTTPError as e:
        if e.code == 404:
            return None
        raise
    paths = re.findall(r"<path [^>]*?/>", svg)
    if not paths:
        sys.exit(f"{name}: no path in the SVG")
    return "".join(paths)


def main() -> None:
    out = ['<svg xmlns="http://www.w3.org/2000/svg" style="display:none" aria-hidden="true">',
           "<!-- Generated by tools/gen-icons.py. Material Symbols (Apache-2.0); crab: Clamor. -->"]
    missing = []
    for entry in ICONS:
        name = entry.rstrip("+")
        variants = [(name, name), (name + "-fill", name + "-fill")] if entry.endswith("+") else [(name, name)]
        for sym, file in variants:
            body = fetch(file)
            if body is None:
                missing.append(file)
                continue
            out.append(f'<symbol id="i-{sym}" viewBox="0 -960 960 960">{body}</symbol>')
    if missing:
        sys.exit("not in Material Symbols " + VERSION + ": " + " ".join(missing))
    out.append(f'<symbol id="i-crab" viewBox="0 0 24 24">{CRAB.format(f="none")}</symbol>')
    out.append(f'<symbol id="i-crab-fill" viewBox="0 0 24 24">{CRAB.format(f="currentColor")}</symbol>')
    out.append("</svg>")
    root = Path(__file__).resolve().parent.parent
    # The dashboard (inlined by portal.rs) and the app's own screens (apps/desktop/ui).
    for dest in (root / "crates/clamor-node/src/icons.svg", root / "apps/desktop/ui/icons.svg"):
        dest.write_text("\n".join(out) + "\n")
        print(f"wrote {dest} ({dest.stat().st_size} bytes)", file=sys.stderr)


if __name__ == "__main__":
    main()
